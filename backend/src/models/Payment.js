import mongoose from 'mongoose';
import { CURRENCY } from '../config/products.js';

export const PAYMENT_STATUS = Object.freeze({
  CREATED: 'CREATED', // Saved here; Razorpay order not created yet
  ORDER_FAILED: 'ORDER_FAILED', // Razorpay order could not be created, so nothing was payable
  PENDING: 'PENDING', // Razorpay order exists; final outcome not known yet
  PAID: 'PAID', // Confirmed captured by Razorpay
  FAILED: 'FAILED' // Latest attempt failed; the customer may still retry on this order
});

/**
 * Every permitted status change. Anything not listed is refused.
 * - FAILED is not final: one order allows several attempts, so a retry can succeed.
 * - PAID and ORDER_FAILED are final: late or out-of-order events cannot undo them.
 */
export const ALLOWED_TRANSITIONS = Object.freeze({
  [PAYMENT_STATUS.CREATED]: [PAYMENT_STATUS.PENDING, PAYMENT_STATUS.ORDER_FAILED],
  [PAYMENT_STATUS.ORDER_FAILED]: [],
  [PAYMENT_STATUS.PENDING]: [PAYMENT_STATUS.PAID, PAYMENT_STATUS.FAILED],
  [PAYMENT_STATUS.FAILED]: [PAYMENT_STATUS.PENDING, PAYMENT_STATUS.PAID],
  [PAYMENT_STATUS.PAID]: []
});

const paymentSchema = new mongoose.Schema(
  {
    // Shown to people and sent to Razorpay as the order's `receipt`
    reference: {
      type: String,
      required: true,
      unique: true,
      trim: true,
      maxlength: 40 // Razorpay's receipt limit
    },
    // Unguessable id for public status lookups, so database ids are never exposed
    statusToken: {
      type: String,
      required: true,
      unique: true
    },
    // Generated by the browser per checkout attempt; makes order creation safe to repeat
    idempotencyKey: {
      type: String,
      required: true,
      unique: true
    },
    // A copy taken at purchase time: later catalog edits must not rewrite history
    product: {
      id: { type: String, required: true },
      name: { type: String, required: true },
      unitPricePaise: { type: Number, required: true, min: 1, validate: Number.isInteger },
      isPlaceholder: { type: Boolean, required: true }
    },
    quantity: {
      type: Number,
      required: true,
      min: 1,
      validate: Number.isInteger
    },
    amountPaise: {
      type: Number,
      required: true,
      min: 1,
      validate: Number.isInteger
    },
    currency: {
      type: String,
      required: true,
      enum: [CURRENCY],
      default: CURRENCY
    },
    status: {
      type: String,
      required: true,
      enum: Object.values(PAYMENT_STATUS),
      default: PAYMENT_STATUS.CREATED
    },
    // Absent until Razorpay responds, hence sparse: many records may lack it
    razorpayOrderId: {
      type: String,
      unique: true,
      sparse: true
    },
    razorpayPaymentId: {
      type: String,
      index: { sparse: true }
    },
    // Result of checking the Checkout callback's signature
    verification: {
      signatureVerified: { type: Boolean, default: false },
      verifiedAt: { type: Date, default: null },
      paymentId: { type: String, default: null } // the payment id the valid signature vouched for
    },
    // What confirmed the final status: the Checkout callback, a status check, or a webhook
    confirmedVia: {
      type: String,
      enum: ['checkout', 'reconciliation', 'webhook', null],
      default: null
    },
    // Last time we asked Razorpay for this order's payments (limits how often we ask)
    lastReconciledAt: { type: Date, default: null },
    // Set when Razorpay's data disagrees with this record, e.g. a different amount.
    // Such a payment is never marked PAID automatically; an administrator must look.
    review: {
      required: { type: Boolean, default: false },
      reason: { type: String, default: null }
    },
    // Copied from Razorpay's payment data. Card numbers, CVVs and UPI PINs are never stored.
    customer: {
      email: { type: String, default: null },
      contact: { type: String, default: null }
    },
    // Why the order or latest attempt failed, for administrators
    failure: {
      code: { type: String, default: null },
      description: { type: String, default: null }
    },
    orderCreatedAt: { type: Date, default: null },
    paidAt: { type: Date, default: null },
    failedAt: { type: Date, default: null }
  },
  {
    timestamps: true
  }
);

paymentSchema.index({ status: 1, createdAt: -1 });

/**
 * Atomically moves a payment to a new status, only if its current status
 * allows it. The check and the write are one database operation, so two
 * concurrent callers cannot both succeed.
 *
 * Returns the updated document, or null if the transition was not permitted.
 */
paymentSchema.statics.transition = function (paymentId, toStatus, fields = {}) {
  const allowedFrom = Object.keys(ALLOWED_TRANSITIONS).filter((from) =>
    ALLOWED_TRANSITIONS[from].includes(toStatus)
  );

  return this.findOneAndUpdate(
    { _id: paymentId, status: { $in: allowedFrom } },
    { $set: { ...fields, status: toStatus } },
    { new: true, runValidators: true }
  );
};

export const Payment = mongoose.model('Payment', paymentSchema);
export default Payment;
